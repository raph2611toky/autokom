"""Safe, per-attempt ACME error extraction for AUTOKOM observability.

Never dump ACME requests, credentials, certificates, tokens or entire logs.
Only extract the certificate authority's human diagnostic for the target host.
"""
from __future__ import annotations

from pathlib import Path
import json
import re

ACME_LOG = Path('/var/log/letsencrypt/letsencrypt.log')


def acme_log_offset(path=None):
    path = Path(path) if path is not None else ACME_LOG
    try:
        return path.stat().st_size if path.is_file() and not path.is_symlink() else 0
    except OSError:
        return 0


def _details(chunk):
    # The official certbot client writes both ``Detail: ...`` and ACME JSON
    # payloads containing a ``detail`` string, depending on the failure type.
    for match in re.finditer(r'(?im)^\s*(?:detail\s*:\s*|["\']detail["\']\s*:\s*)(["\']?)([^\r\n]+)', chunk):
        text = match.group(2).strip().rstrip(',').strip('"\' ')
        yield text


def acme_failure_detail(domain, *, since=0, path=None):
    path = Path(path) if path is not None else ACME_LOG
    if not re.fullmatch(r'[a-z0-9.-]{1,253}', domain.lower()):
        return 'journal ACME non disponible'
    try:
        if path.is_symlink() or not path.is_file():
            return 'cause ACME détaillée indisponible (voir journal Certbot)'
        size = path.stat().st_size
        # Read only data generated by *this* attempt, never reuse an older
        # failure after a different ACME invocation. Handle log truncation.
        start = min(max(0, since), size)
        with path.open('rb') as handle:
            handle.seek(max(start, size - 196608))
            text = handle.read(196608).decode('utf-8', 'replace')
    except OSError:
        return 'journal ACME inaccessible (voir /var/log/letsencrypt/letsencrypt.log)'
    details = [x for x in _details(text) if domain.lower() in x.lower()]
    if details:
        detail = details[-1].replace('\\n', ' ').replace('\\r',' ')
        # The HTTP-01 token is ephemeral; do not propagate it into AUTOKOM logs.
        detail = re.sub(r'(/\.well-known/acme-challenge/)[^/?#\s]+', r'\1<token-masque>', detail)
        # No terminal escape sequences / multiline output. Max bounded output.
        detail = re.sub(r'[\x00-\x1f\x7f\x1b]', ' ', detail)[:440]
        if re.search('Timeout during connect|Connection refused', detail, re.I):
            return detail + ' ; vérifier TCP/80 dans le VPC GCP, UFW et l’écoute Nginx'
        if re.search('Invalid response|unauthorized', detail, re.I):
            return detail + ' ; vérifier le virtual host et le chemin /.well-known/acme-challenge/'
        return detail
    return ('cause précise non présente dans cette tentative : consulter le journal Certbot '
            'et tester HTTP/80 depuis une autre machine')
