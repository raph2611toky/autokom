#!/usr/bin/env python3
"""AUTOKOM internal-only Docker ingress via host Nginx loopback relay.

This module never grants egress, publishes a Docker port, or executes arbitrary
commands. Caller supplies the trusted broker's narrowly allowlisted run().
New files are generated by AUTOKOM and are never adopted if pre-existing.
"""
from __future__ import annotations

import ipaddress
import json
import os
from pathlib import Path
import re
import socket
import stat
import tempfile
import time
from urllib.request import Request, build_opener, HTTPRedirectHandler, ProxyHandler

MODE = 'nginx-internal-v1'
NAME_RE = re.compile(r'^autokom-[0-9a-f]{20}$')


class IngressError(Exception):
    """Only code and fixed, non-secret explanation may cross the broker boundary."""

    def __init__(self, code, message):
        if not re.fullmatch(r'AUTOKOM_[A-Z0-9_]{3,80}', code):
            raise ValueError('Invalid safe diagnostic code')
        self.code = code
        super().__init__(f'{code}: {message}')


def _name(name):
    if not isinstance(name, str) or not NAME_RE.fullmatch(name):
        raise IngressError('AUTOKOM_INGRESS_INVALID_NAME', 'Identifiant de publication invalide.')
    return name


def _layout(name, available, enabled):
    _name(name)
    available = Path(available)
    enabled = Path(enabled)
    for directory in (available, enabled):
        if directory.is_symlink() or not directory.is_dir():
            raise IngressError('AUTOKOM_NGINX_DIRECTORY_INVALID', 'Arborescence Nginx non conforme.')
    basename = 'autokom-ingress-' + name[8:] + '.conf'
    return available / basename, enabled / basename


def _atomic_write(path, contents):
    if path.is_symlink():
        raise IngressError('AUTOKOM_INGRESS_FILE_TAMPERED', 'Configuration Nginx non conforme.')
    with tempfile.NamedTemporaryFile('w', dir=path.parent, prefix='.autokom-ingress-', delete=False, encoding='utf-8') as stream:
        temp_path = Path(stream.name)
        stream.write(contents)
    try:
        os.chmod(temp_path, 0o644)
        os.replace(temp_path, path)
    finally:
        temp_path.unlink(missing_ok=True)


def _docker_network_info(network, execute):
    # The network identifier is generated by the trusted broker, not client input.
    raw = execute(['docker', 'network', 'inspect', network], timeout=12, max_output=16384)
    try:
        data = json.loads(raw)
        if len(data) != 1 or data[0]['Name'] != network:
            raise ValueError('Unexpected Docker network')
        item = data[0]
        if item['Internal'] is not True or item['Driver'] != 'bridge':
            raise ValueError('Non-isolated Docker network')
        subnets = [ipaddress.ip_network(c['Subnet'], strict=False) for c in item['IPAM']['Config']]
        subnets = [n for n in subnets if isinstance(n, ipaddress.IPv4Network)]
        if not subnets:
            raise ValueError('No IPv4 subnet')
        return item, subnets
    except (ValueError, TypeError, KeyError, IndexError, ipaddress.AddressValueError) as exc:
        raise IngressError('AUTOKOM_NETWORK_NOT_PRIVATE', 'Réseau Docker interne invalide ou non vérifiable.') from exc


def container_ipv4(name, network, execute):
    _name(name)
    if not isinstance(network, str) or not NAME_RE.fullmatch(network):
        raise IngressError('AUTOKOM_NETWORK_INVALID_NAME', 'Nom du réseau Docker invalide.')
    info, subnets = _docker_network_info(network, execute)
    raw = execute(['docker','container','inspect',name,'--format','{{json .NetworkSettings.Networks}}'],
                  timeout=12, max_output=16384)
    try:
        networks = json.loads(raw)
        if not isinstance(networks, dict) or set(networks) != {network}:
            raise ValueError('Container is attached to unexpected networks')
        entry = networks[network]
        if entry.get('NetworkID') != info['Id']:
            raise ValueError('Network identity mismatch')
        address = ipaddress.ip_address(entry['IPAddress'])
        if not isinstance(address, ipaddress.IPv4Address):
            raise ValueError('IPv6 not supported')
        if (not address.is_private or address.is_loopback or address.is_link_local
                or address.is_multicast or address.is_unspecified or address.is_reserved):
            raise ValueError('Unexpected IPv4 address')
        if not any(address in subnet for subnet in subnets):
            raise ValueError('Outside Docker managed subnet')
        return str(address)
    except (ValueError, TypeError, KeyError, IndexError) as exc:
        raise IngressError('AUTOKOM_CONTAINER_NETWORK_INVALID',
                           'Le conteneur ne respecte pas son réseau privé exclusif.') from exc


def pick_loopback_port():
    """The broker serializes deployments; validation after Nginx reload detects races."""
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as sock:
        sock.bind(('127.0.0.1', 0))
        port = sock.getsockname()[1]
    if not 1024 <= port <= 65535:
        raise IngressError('AUTOKOM_INGRESS_PORT_INVALID', 'Port local alloué non conforme.')
    return port


def _probe_path(name):
    return '/__autokom_ingress_probe_' + _name(name)[8:]


def render_relay(name, external_port, address, internal_port):
    _name(name)
    address = ipaddress.ip_address(address)
    if not isinstance(address, ipaddress.IPv4Address) or not address.is_private or address.is_loopback:
        raise IngressError('AUTOKOM_INGRESS_IP_INVALID', 'Adresse amont refusée.')
    if type(external_port) is not int or not 1024 <= external_port <= 65535:
        raise IngressError('AUTOKOM_INGRESS_PORT_INVALID', 'Port local invalide.')
    if type(internal_port) is not int or not 1 <= internal_port <= 65535:
        raise IngressError('AUTOKOM_INGRESS_TARGET_INVALID', 'Port applicatif invalide.')
    probe = _probe_path(name)
    marker = name[8:]
    return (f'# AUTOKOM {MODE}; generated; local-only; no Docker published port\n'
            f'server {{\n    listen 127.0.0.1:{external_port};\n    server_name _;\n'
            f'    access_log off;\n    client_max_body_size 16m;\n'
            f'    location = {probe} {{\n'
            f'        add_header X-Autokom-Ingress "{marker}" always;\n'
            f'        return 204;\n    }}\n'
            f'    location / {{\n        proxy_pass http://{address}:{internal_port};\n'
            '        proxy_http_version 1.1;\n'
            '        proxy_set_header Host $http_host;\n'
            '        proxy_set_header X-Forwarded-For $http_x_forwarded_for;\n'
            '        proxy_set_header X-Forwarded-Proto $http_x_forwarded_proto;\n'
            '        proxy_set_header Upgrade $http_upgrade;\n'
            '        proxy_set_header Connection "upgrade";\n'
            '        proxy_connect_timeout 5s;\n'
            '        proxy_read_timeout 60s;\n'
            '    }\n}\n')


class _NoRedirect(HTTPRedirectHandler):
    def redirect_request(self, *args, **kwargs):
        return None


def probe_relay(name, port):
    if type(port) is not int or not 1024 <= port <= 65535:
        return False
    path = _probe_path(name)
    request = Request(f'http://127.0.0.1:{port}{path}')
    try:
        with build_opener(ProxyHandler({}), _NoRedirect()).open(request, timeout=2) as response:
            return response.status == 204 and response.headers.get('X-Autokom-Ingress') == name[8:]
    except Exception:
        return False


def preflight(execute, available, enabled):
    _layout('autokom-'+'0'*20, available, enabled)
    try:
        execute(['docker', 'info', '--format', '{{.ServerVersion}}'], timeout=12)
    except Exception as exc:
        raise IngressError('AUTOKOM_DOCKER_UNAVAILABLE', 'Démon Docker indisponible.') from exc
    try:
        execute(['nginx', '-t'], timeout=12)
    except Exception as exc:
        raise IngressError('AUTOKOM_NGINX_INVALID', 'Configuration Nginx non valide.') from exc
    return True


def _remove_config(name, *, execute, available, enabled, reload=True):
    """Detach an ingress from Nginx BEFORE deleting its source file.

    Removing the file while the enabled symlink is still visible causes a
    transient invalid Nginx configuration, even on otherwise healthy hosts.
    If nginx -t/reload refuses the detach, restore the symlink and preserve
    the source file for a safe operator retry.
    """
    path, link = _layout(name, available, enabled)
    if (path.is_symlink() or (link.is_symlink() and link.resolve() != path)
            or (link.exists() and not link.is_symlink())):
        raise IngressError('AUTOKOM_INGRESS_FILE_TAMPERED', 'Fichier ingress non géré détecté.')
    had_link = link.is_symlink()
    had_file = path.is_file()
    if had_link:
        link.unlink()
    try:
        if had_link and reload:
            execute(['nginx', '-t'], timeout=12)
            execute(['systemctl', 'reload', 'nginx'], timeout=15)
    except Exception as exc:
        # The existing valid relay must remain usable if detach fails.
        if had_file and not link.exists() and not link.is_symlink():
            link.symlink_to(path)
        raise IngressError('AUTOKOM_INGRESS_DETACH_FAILED',
                           'Relais Nginx conservé : retrait non validé.') from exc
    if had_file:
        path.unlink()
    return had_link or had_file


def create(name, network, internal_port, *, execute, available, enabled, attempts=4):
    path, link = _layout(name, available, enabled)
    if path.exists() or path.is_symlink() or link.exists() or link.is_symlink():
        raise IngressError('AUTOKOM_INGRESS_ALREADY_EXISTS', 'Ingress présent hors transaction.')
    address = container_ipv4(name, network, execute)
    for _ in range(attempts):
        port = pick_loopback_port()
        try:
            _atomic_write(path, render_relay(name, port, address, internal_port))
            link.symlink_to(path)
            execute(['nginx','-t'], timeout=12)
            execute(['systemctl','reload','nginx'], timeout=15)
            for i in range(8):
                if probe_relay(name, port):
                    return {'port': port, 'container_ip': address, 'internal_port': internal_port, 'ingress_mode': MODE}
                time.sleep(0.3)
        except Exception as exc:
            try:
                _remove_config(name, execute=execute, available=available, enabled=enabled)
            except IngressError as cleanup_exc:
                if cleanup_exc.code != 'AUTOKOM_INGRESS_DETACH_FAILED':
                    raise IngressError('AUTOKOM_INGRESS_CLEANUP_FAILED',
                                       'Nettoyage Nginx incomplet.') from exc
                # This candidate was never approved as a release.  If a failed
                # reload prevents orderly detachment, discard ONLY these two
                # newly-created files; never apply this fallback to a live
                # release's ingress.remove().
                _remove_config(name, execute=execute, available=available,
                               enabled=enabled, reload=False)
            except Exception:
                raise IngressError('AUTOKOM_INGRESS_CLEANUP_FAILED',
                                   'Nettoyage Nginx incomplet.') from exc
            if isinstance(exc, IngressError):
                raise
            raise IngressError('AUTOKOM_INGRESS_NGINX_FAILED', 'Nginx a refusé le relais local.') from exc
        _remove_config(name, execute=execute, available=available, enabled=enabled)
    raise IngressError('AUTOKOM_INGRESS_BIND_FAILED', 'Impossible de réserver un relais Nginx sur loopback.')


def remove(name, *, execute, available, enabled):
    try:
        return _remove_config(name, execute=execute, available=available, enabled=enabled)
    except IngressError:
        raise
    except Exception as exc:
        raise IngressError('AUTOKOM_INGRESS_CLEANUP_FAILED', 'Nettoyage du relais local incomplet.') from exc


def reconcile(state, *, execute, available, enabled):
    """Reconcile a previously approved relay if Docker changes only its internal IP.

    Never adopt missing/tampered configurations; operator may have disabled it.
    This is safe to call on broker start or periodically, without client input.
    """
    if not isinstance(state, dict) or state.get('ingress_mode') != MODE:
        return False
    name = _name(state.get('name'))
    network = state.get('network')
    path, link = _layout(name, available, enabled)
    if (not path.is_file() or path.is_symlink() or not link.is_symlink()
            or link.resolve() != path):
        raise IngressError('AUTOKOM_INGRESS_FILE_MISSING', 'Relais Nginx absent ou altéré.')
    expected = render_relay(name, state['port'], state['container_ip'], state['internal_port'])
    address = container_ipv4(name, network, execute)
    newconf = render_relay(name, state['port'], address, state['internal_port'])
    actual = path.read_text(encoding='utf-8')
    # Crash-safe reconciliation: a prior reload may have succeeded just before
    # persisting the updated state. Accept ONLY the currently verified Docker IP.
    if actual == newconf:
        if state['container_ip'] != address:
            state['container_ip'] = address
            return True
        return False
    if actual != expected:
        raise IngressError('AUTOKOM_INGRESS_FILE_TAMPERED', 'Relais Nginx modifié hors AUTOKOM.')
    _atomic_write(path, newconf)
    try:
        execute(['nginx','-t'], timeout=12)
        execute(['systemctl','reload','nginx'], timeout=15)
    except Exception as exc:
        _atomic_write(path, expected)
        try:
            execute(['nginx','-t'], timeout=12)
            execute(['systemctl','reload','nginx'], timeout=15)
        except Exception:
            pass
        raise IngressError('AUTOKOM_INGRESS_RECONCILE_FAILED', 'Actualisation automatique du relais impossible.') from exc
    state['container_ip'] = address
    return True


def diagnose(execute, available, enabled, state_root):
    """Read-only platform doctor: Docker, Nginx and every managed current release."""
    preflight(execute, available, enabled)
    root = Path(state_root)
    if root.is_symlink() or not root.is_dir():
        raise IngressError('AUTOKOM_STATE_DIRECTORY_INVALID', 'Répertoire runtime absent ou non conforme.')
    checked = 0
    for folder in root.iterdir():
        if folder.is_symlink() or not folder.is_dir() or not re.fullmatch(r'[a-f0-9]{8}-(?:[a-f0-9]{4}-){3}[a-f0-9]{12}', folder.name):
            continue
        file = folder / 'current.json'
        if not file.is_file() or file.is_symlink():
            continue
        try:
            state = json.loads(file.read_text(encoding='utf-8'))
        except (OSError, ValueError, UnicodeError) as exc:
            raise IngressError('AUTOKOM_STATE_CORRUPT', 'État de publication actif non lisible.') from exc
        if not isinstance(state, dict) or state.get('environment_id') != folder.name:
            raise IngressError('AUTOKOM_STATE_CORRUPT', 'État de publication actif incohérent.')
        if state.get('ingress_mode') != MODE:
            continue  # Legacy releases are not silently migrated during a read-only check.
        name = _name(state.get('name'))
        path, link = _layout(name, available, enabled)
        if (not path.is_file() or path.is_symlink() or not link.is_symlink()
                or link.resolve() != path):
            raise IngressError('AUTOKOM_INGRESS_FILE_MISSING', 'Relais actif absent ou altéré.')
        if path.read_text(encoding='utf-8') != render_relay(name,state['port'],state['container_ip'],state['internal_port']):
            raise IngressError('AUTOKOM_INGRESS_FILE_TAMPERED', 'Configuration de relais actif modifiée.')
        actual_ip = container_ipv4(name,state['network'],execute)
        if actual_ip != state['container_ip']:
            raise IngressError('AUTOKOM_INGRESS_IP_DRIFT', 'Adresse du conteneur modifiée ; réconciliation automatique en cours.')
        if not probe_relay(name,state['port']):
            raise IngressError('AUTOKOM_INGRESS_NOT_READY', 'Relais Nginx actif non joignable.')
        raw = execute(['docker','container','inspect',name,
                       '--format','{{json .NetworkSettings.Ports}}'], timeout=12,max_output=8192)
        try:
            published = json.loads(raw)
            if not isinstance(published,dict) or any(v not in (None,[]) for v in published.values()):
                raise ValueError('Docker port published')
        except (ValueError,TypeError) as exc:
            raise IngressError('AUTOKOM_CONTAINER_PORT_EXPOSED', 'Conteneur publié hors réseau interne.') from exc
        target = state.get('healthcheck','/')
        if (not isinstance(target,str) or not target.startswith('/') or len(target)>128
                or any(v in target for v in ('?','#','%','\\','\r','\n'))):
            raise IngressError('AUTOKOM_HEALTHCHECK_INVALID', 'Chemin de santé enregistré non conforme.')
        try:
            request = Request(f'http://127.0.0.1:{state["port"]}{target}',headers={'Host':'localhost'})
            with build_opener(ProxyHandler({}),_NoRedirect()).open(request,timeout=3) as response:
                if not 200 <= response.status < 400:
                    raise ValueError('Bad status')
        except Exception as exc:
            raise IngressError('AUTOKOM_APPLICATION_UNHEALTHY', 'Application active sans réponse de santé.') from exc
        checked += 1
    return {'ingresses_checked':checked, 'private_ingress_preflight':True}
